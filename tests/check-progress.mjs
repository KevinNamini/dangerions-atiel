import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync(new URL('../dist/progress.js',import.meta.url),'utf8'),context);
const at='2026-10-16T10:07:00Z',old='2026-10-15T10:07:00Z';
const names=['A','B','C','D','E','F'];
function data(current=[1000,900,800,700,600,500],previous=[1000,900,800,700,600,500]){
  return {updatedAt:at,failures:[],players:names.map((name,i)=>({name,itemLevel:current[i],observedAt:at})),snapshots:[{capturedAt:old,roster:names,values:Object.fromEntries(names.map((name,i)=>[name,{itemLevel:previous[i],observedAt:old}]))}]};
}
const metrics=d=>context.window.dangerionsProgress(d,Date.parse(at));
const changed=data([1000,900,800,700,1100,500]);
const m=metrics(changed);
assert.equal(m.movement(changed.players[4]).value,4);
assert.equal(m.movement(changed.players[0]).value,-1);
assert.equal(m.delta(changed.players[0]),0,'A player can lose a place without losing Item-Level.');
assert.equal(m.movement(changed.players[5]).value,0);
const negative=data([1000,900,800,700,600,500],[1000,1100,800,700,600,500]);
assert.equal(metrics(negative).delta(negative.players[1]),-200);
const tied=data([1000,1000,800,700,600,500]);
assert.equal(metrics(tied).rank(tied.players[0]),1);assert.equal(metrics(tied).rank(tied.players[1]),1);assert.equal(metrics(tied).rank(tied.players[2]),3);
assert.equal(metrics(tied).movement(tied.players[1]).value,1);
const noHistory=data();noHistory.snapshots=[];
assert.equal(metrics(noHistory).delta(noHistory.players[0]),null,'Daily archive must not masquerade as a 24-hour capture.');
const late=data();late.snapshots[0].capturedAt='2026-10-15T11:07:00Z';
Object.values(late.snapshots[0].values).forEach(v=>v.observedAt=late.snapshots[0].capturedAt);
assert.equal(metrics(late).delta(late.players[0]),0,'A one-hour timing deviation is explicit but usable.');
late.snapshots[0].capturedAt='2026-10-15T11:13:00Z';
assert.equal(metrics(late).baseline,null,'A larger gap must not invent a precise 24-hour comparison.');
const partial=data();delete partial.snapshots[0].values.C;
assert.equal(metrics(partial).movement(partial.players[0]).value,null,'Incomplete cohorts cannot establish rank changes.');
assert.equal(metrics(partial).delta(partial.players[0]),0,'Verified individual Item-Level comparison remains usable.');
const retained=data([1000,1135,800,700,600,500]);retained.failures=[{name:'B'}];
retained.players[1].observedAt='2026-10-16T09:57:00Z';
const retainedOriginal=JSON.stringify(retained);
assert.equal(metrics(retained).delta(retained.players[1]),235,'A failed retry must not erase a recently verified gain.');
assert.equal(metrics(retained).movement(retained.players[1]).value,1,'Recent verified observations still form a complete ranking.');
assert.equal(metrics(retained).movement(retained.players[0]).value,-1);
retained.players[1].observedAt='2026-10-16T09:00:00Z';
assert.equal(metrics(retained).delta(retained.players[1]),235,'A single missed hourly update retains the verified comparison.');
retained.players[1].observedAt='2026-10-16T09:57:00Z';
assert.equal(JSON.stringify(retained),retainedOriginal,'Showing the last verified comparison never changes its timestamp or failure record.');
const stale=structuredClone(retained);stale.players[1].observedAt='2026-10-16T08:06:59Z';
assert.equal(metrics(stale).delta(stale.players[1]),null);assert.equal(metrics(stale).movement(stale.players[0]).value,null);
const ageBoundary=structuredClone(retained);ageBoundary.players[1].observedAt='2026-10-16T08:10:00Z';
assert.equal(context.window.dangerionsProgress(ageBoundary,Date.parse(at)+4*60000).delta(ageBoundary.players[1]),null,'Actual observation age controls expiry even while the feed itself is newer.');
const future=data();future.players[1].observedAt='2026-10-16T10:08:00Z';
assert.equal(metrics(future).delta(future.players[1]),null,'Future observations cannot establish a comparison.');
const unknown=data();delete unknown.players[1].observedAt;
assert.equal(metrics(unknown).delta(unknown.players[1]),null,'Missing timestamps must never produce a gain.');
assert.equal(context.window.dangerionsProgress(data(),Date.parse(at)+3*3600000).delta(data().players[0]),null,'Old current data must be labelled, not described as current.');
const newcomer=data();newcomer.snapshots[0].roster=names.slice(0,-1);delete newcomer.snapshots[0].values.F;
assert.equal(metrics(newcomer).movement(newcomer.players[5]).reason,'new');
// Startup may use yesterday's recorded observations, explicitly as provisional.
const warm=data([1000,900,800,700,1100,500]);
warm.hourlyStartedAt=at;
warm.history=[{day:'2026-10-15',values:Object.fromEntries(names.slice(0,-1).map((name,i)=>[name,{itemLevel:[1000,900,800,700,600][i],observedAt:'2026-10-15T17:37:00Z'}]))}];
warm.snapshots=[{capturedAt:at,roster:names,values:Object.fromEntries(warm.players.map(p=>[p.name,{itemLevel:p.itemLevel,observedAt:at}]))}];
const saved=JSON.stringify(warm),provisional=metrics(warm);
assert.equal(provisional.provisional,true);
assert.equal(provisional.delta(warm.players[4]),500);
assert.equal(provisional.movement(warm.players[4]).value,4);
assert.equal(provisional.movement(warm.players[5]).reason,'new');
assert.equal(provisional.delta(warm.players[5]),null,'A newcomer has no invented prior-day value.');
assert.equal(provisional.baseline.capturedAt,'2026-10-15T17:37:00.000Z');
assert.equal(JSON.stringify(warm),saved,'Reading the archive never rewrites daily values or creates hourly captures.');
const reportedStart=structuredClone(warm);
reportedStart.history[0].values.F={itemLevel:0,level:1,observedAt:'2026-10-15T23:00:00+02:00',source:'user-reported',reportedBy:'Kevin',recordedAt:at};
reportedStart.players[5].itemLevel=750;
const manual=metrics(reportedStart);
assert.equal(manual.complete,true,'A disclosed start at a different time does not invalidate the official cohort.');
assert.equal(manual.delta(reportedStart.players[5]),750);
assert.equal(manual.movement(reportedStart.players[5]).value,1);
assert.equal(manual.delta(reportedStart.players[4]),500,'Official comparisons keep their original observation time.');
assert.equal(manual.baseline.capturedAt,'2026-10-15T17:37:00.000Z');
const unlabelled=structuredClone(reportedStart);delete unlabelled.history[0].values.F.source;
assert.equal(metrics(unlabelled).delta(unlabelled.players[5]),null,'Zero is accepted only as an explicitly attributed start.');
const reportedNegative=structuredClone(reportedStart);reportedNegative.history[0].values.F.itemLevel=-1;
assert.equal(metrics(reportedNegative).delta(reportedNegative.players[5]),null);
const reportedTransition=structuredClone(reportedStart);
reportedTransition.updatedAt='2026-10-17T10:07:00Z';reportedTransition.players.forEach(p=>p.observedAt=reportedTransition.updatedAt);
assert.equal(context.window.dangerionsProgress(reportedTransition,Date.parse(reportedTransition.updatedAt)).delta(reportedTransition.players[5]),250,'Later 24-hour comparisons use real captures; the manual zero remains historical.');
const transition=structuredClone(warm);
transition.updatedAt='2026-10-17T10:07:00Z';transition.players.forEach(p=>{p.observedAt=transition.updatedAt;p.itemLevel+=10});
const full=context.window.dangerionsProgress(transition,Date.parse(transition.updatedAt));
assert.equal(full.provisional,false);
assert.equal(full.delta(transition.players[4]),10,'Automatically use the real 24-hour baseline instead of the provisional daily stand.');
assert.equal(full.delta(transition.players[5]),10,'A newcomer becomes comparable once their own baseline exists.');
const incomplete=structuredClone(warm);
incomplete.history.unshift({day:'2026-10-14',values:{F:{itemLevel:400,observedAt:'2026-10-14T17:37:00Z'}}});
assert.equal(metrics(incomplete).movement(incomplete.players[5]).reason,'incomplete','An older known player with a missing day is not labelled new.');
assert.equal(metrics(incomplete).movement(incomplete.players[0]).value,null);
const badDay=structuredClone(warm);badDay.history[0].day='2026-10-14';
assert.equal(metrics(badDay).baseline,null,'No silent fallback across missing days.');
const staleDay=structuredClone(warm);Object.values(staleDay.history[0].values).forEach(v=>v.observedAt='2026-10-14T17:37:00Z');
assert.equal(metrics(staleDay).baseline,null,'Carried-forward values do not become fresh daily observations.');
const expired=structuredClone(transition);expired.snapshots=[];
assert.equal(context.window.dangerionsProgress(expired,Date.parse(expired.updatedAt)).baseline,null,'Do not reuse the startup fallback for later collection outages.');
// 24 hours means elapsed time, even across Berlin's autumn DST change.
const dst=data();dst.updatedAt='2026-10-25T10:00:00Z';dst.players.forEach(p=>p.observedAt=dst.updatedAt);
dst.snapshots[0].capturedAt='2026-10-24T10:00:00Z';Object.values(dst.snapshots[0].values).forEach(v=>v.observedAt=dst.snapshots[0].capturedAt);
assert.equal(context.window.dangerionsProgress(dst,Date.parse(dst.updatedAt)).delta(dst.players[0]),0);
console.log('PASS: rank rises/falls/ties/newcomers, independent IL gain, missing/partial/stale captures, bounded 24-hour comparison and DST.');
